#!/usr/bin/env bash
# Writes the hidraw/uinput udev rule from the VENDOR_IDS list in upstream's
# install-linux.sh, so the vendor list tracks each release.
#
# Unlike upstream's installer this grants access via uaccess only (the
# logged-in seat user), not MODE="0666", so other local users and system
# services cannot read raw HID reports from these devices.
#
#   scripts/gen-udev-rules.sh path/to/install-linux.sh > 69-openmouse-bridge.rules
set -euo pipefail

installer="${1:?usage: gen-udev-rules.sh install-linux.sh}"
ids_line="$(grep -m1 -E '^VENDOR_IDS="[0-9a-fA-F ]+"$' "$installer")" ||
  { echo "error: no VENDOR_IDS line in $installer" >&2; exit 1; }
ids="${ids_line#VENDOR_IDS=\"}"
ids="${ids%\"}"
[ -n "${ids// /}" ] || { echo "error: VENDOR_IDS is empty" >&2; exit 1; }

echo "# OpenMouse Bridge: let the signed-in user reach supported mice and keyboards over hidraw."
echo "# Generated by scripts/gen-udev-rules.sh from upstream install-linux.sh."
for vid in $(tr 'A-F' 'a-f' <<<"$ids" | tr ' ' '\n' | sed '/^$/d' | sort -u); do
  [[ "$vid" =~ ^[0-9a-f]{4}$ ]] || { echo "error: bad vendor id: $vid" >&2; exit 1; }
  printf 'SUBSYSTEM=="hidraw", ATTRS{idVendor}=="%s", TAG+="uaccess"\n' "$vid"
done
echo "# The button listener presses keys and side buttons through a virtual keyboard and mouse."
echo 'KERNEL=="uinput", SUBSYSTEM=="misc", MODE="0660", TAG+="uaccess", OPTIONS+="static_node=uinput"'
