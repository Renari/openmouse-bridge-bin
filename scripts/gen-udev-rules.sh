#!/usr/bin/env bash
# Writes the hidraw/uinput udev rule and the helper it runs from the copies
# embedded in upstream's install-linux.sh, so both track each release:
#
#   scripts/gen-udev-rules.sh path/to/install-linux.sh [DIR]
#
# creates DIR/69-openmouse-bridge.rules and DIR/openmouse-bridge-is-mouse
# (DIR defaults to the current directory).
#
# Upstream installs both under /etc/udev; this package ships them under
# /usr/lib/udev. Where upstream picks MODE="0666" on systems without logind,
# this always grants access via uaccess only (the logged-in seat user), so
# other local users and system services cannot read raw HID reports.
set -euo pipefail

installer="${1:?usage: gen-udev-rules.sh install-linux.sh [DIR]}"
dir="${2:-.}"
rule_name=69-openmouse-bridge.rules
helper_name=openmouse-bridge-is-mouse
helper_path="/usr/lib/udev/${helper_name}"

die() { echo "error: $*" >&2; exit 1; }

# Prints the body of the quoted heredoc that ends with the line $1.
heredoc() {
  awk -v end="$1" '
    $0 == end { found = 1; exit }
    inside { print }
    index($0, "<<'\''" end "'\''") { inside = 1 }
    END { exit !found }
  ' "$installer"
}

# Moves upstream's /etc/udev paths to where this package installs the files.
relocate() {
  sed -e "s|/etc/udev/rules\.d/${rule_name}|/usr/lib/udev/rules.d/${rule_name}|g" \
    -e "s|/etc/udev/${helper_name}|${helper_path}|g"
}

rule_body="$(heredoc OPENMOUSE_UDEV_RULE)" || die "no OPENMOUSE_UDEV_RULE heredoc in $installer"
helper_body="$(heredoc OPENMOUSE_UDEV_HELPER)" || die "no OPENMOUSE_UDEV_HELPER heredoc in $installer"

rules="$(grep -v -E '^[[:space:]]*(#|$)' <<<"$rule_body" |
  sed 's|@ACCESS@|TAG+="uaccess"|g' | relocate)"
hidraw="$(grep -c '^SUBSYSTEM=="hidraw"' <<<"$rules" || true)"
[ "$hidraw" -eq 1 ] || die "expected one hidraw rule upstream, found $hidraw"
grep '^SUBSYSTEM=="hidraw"' <<<"$rules" | grep -qF "PROGRAM=\"/bin/sh ${helper_path} %S%p\"" ||
  die "the hidraw rule no longer runs ${helper_name} the way this script expects"
grep -q '^KERNEL=="uinput"' <<<"$rules" || die "no uinput rule upstream"
! grep -qE '@[A-Z_]+@|/etc/udev|MODE="0?[0-7][0-7][1-7]"' <<<"$rules" ||
  die "the generated rule has an unknown placeholder, an /etc path or world access"

helper="$(relocate <<<"$helper_body")"
[ "$(head -n1 <<<"$helper")" = "#!/bin/sh" ] || die "the helper is not a /bin/sh script"
! grep -q '/etc/udev' <<<"$helper" || die "the helper still refers to /etc/udev"
sh -n <<<"$helper" || die "the helper does not parse"

mkdir -p "$dir"
{
  echo "# OpenMouse Bridge: let the signed-in user reach mice over hidraw."
  echo "# Generated by scripts/gen-udev-rules.sh from upstream install-linux.sh."
  echo "# The hidraw rule matches every hidraw node of a USB device with a mouse"
  echo "# interface (a mouse or its receiver), including the vendor interface its"
  echo "# settings go through. The uinput rule lets the button listener press keys"
  echo "# and side buttons through a virtual keyboard and mouse."
  printf '%s\n' "$rules"
} >"${dir}/${rule_name}"
printf '%s\n' "$helper" >"${dir}/${helper_name}"
